#!/usr/bin/env python3
"""Generate roblox/SHANKPIT_460_INSTALL.luau -- ONE paste that builds the 460 layer in Studio.

Why this exists beside the .rbxmx: the model needs Insert From File and then six drag-and-drop steps (Script and
ModuleScripts into ServerScriptService, LocalScript into StarterPlayerScripts, two settings toggles), and every one
of those is a way to end up with a lobby that looks finished and does nothing on screen. This installer is the SAME
PARTS list as the model, emitted as a chunk you paste into Studio's Command Bar: it creates the folder, the
ModuleScripts, the server Script (Disabled) and the client LocalScript in the places they have to be, replaces a
previous install rather than duplicating it, and prints what it did and what is left for a human.

It deliberately does NOT change place security settings (HttpService, API services): those are the place's, and an
installer that flips them silently would be doing more than it says. It reports their state instead.

Usage: python3 roblox/tools/build_installer.py [out.luau]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_rbxmx as model  # noqa: E402  -- one PARTS list, two artifacts, so they cannot disagree

ROOT = model.ROOT
SRC = model.SRC
OUT = os.path.join(ROOT, "SHANKPIT_460_INSTALL.luau")

FOLDER = "SHANKPIT460"
SERVER_ROOT = "ServerScriptService/" + FOLDER
CLIENT_ROOT = "StarterPlayer/StarterPlayerScripts"


def long_bracket(source):
    """Pick a long-bracket level the source cannot close by accident: [==[ ... ]==] etc."""
    level = 0
    while ("]" + "=" * level + "]") in source:
        level += 1
    eq = "=" * level
    return "[" + eq + "[", "]" + eq + "]"


def path_for(cls, name):
    # The client script must live in StarterPlayerScripts or it never runs for a player; everything else runs
    # inside the folder in ServerScriptService, where a Script nested in a Folder still executes.
    if cls == "LocalScript":
        return CLIENT_ROOT + "/" + name
    return SERVER_ROOT + "/" + name


def main(argv):
    out_path = argv[1] if len(argv) > 1 else OUT
    parts = [{"path": "ServerScriptService/" + FOLDER, "cls": "Folder", "name": FOLDER, "source": None}]
    total = 0
    for fname, cls, name in model.PARTS:
        with open(os.path.join(SRC, fname), "r", encoding="utf-8") as f:
            source = f.read()
        total += len(source)
        parts.append({"path": path_for(cls, name), "cls": cls, "name": name, "source": source})

    rows = []
    for part in parts:
        src_field = ""
        if part["source"] is not None:
            open_b, close_b = long_bracket(part["source"])
            if part["source"].endswith("]"):
                # A source ending in ']' would glue onto the closing bracket; a newline keeps it unambiguous.
                src_field = ", source = %s\n%s\n%s" % (open_b, part["source"], close_b)
            else:
                src_field = ", source = %s%s%s" % (open_b, part["source"], close_b)
        disabled = "true" if part["cls"] == "Script" else "nil"
        rows.append(
            '    { path = "%s", class = "%s", name = "%s", disabled = %s%s },'
            % (part["path"], part["cls"], part["name"], disabled, src_field)
        )

    chunk = (HEAD.replace("@@PARTS@@", "\n".join(rows))
                .replace("@@SERVER@@", '"%s"' % SERVER_ROOT)
                .replace("@@CLIENT@@", '"%s"' % CLIENT_ROOT))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(chunk)

    # Prove the artifact is what we meant: every embedded source must appear verbatim in the file we just wrote,
    # and the count must match. A paste script whose string got mangled is worse than none.
    written = open(out_path, "r", encoding="utf-8").read()
    for part in parts:
        if part["source"] is not None and part["source"] not in written:
            raise SystemExit("%s: embedded source is not verbatim in the installer" % part["name"])
    print("%s: %d instances, %d bytes of Luau" % (os.path.relpath(out_path, ROOT), len(parts), total))


HEAD = r'''-- SHANKPIT460 -- Roblox Studio Command Bar installer.
-- GENERATED by roblox/tools/build_installer.py from roblox/src/*.lua. Do not edit this file: edit src/ and run
-- `make roblox-install` (or `make roblox-model`, which builds this and the .rbxmx from one PARTS list).
--
-- HOW TO USE: open the base place (shankpit_roblox.rbxl) in Studio, open View -> Command Bar, paste this WHOLE
-- file, press Enter once. It replaces any previous SHANKPIT460 install rather than duplicating it.
--
-- What it does NOT do, on purpose: it does not enable HTTP requests or Studio API access (those are place
-- settings, reported below, never flipped silently), it does not fill in IDUNA/WOTAN hosts (set the attributes
-- IdunaBase / WotanBase on the `lobby` Script to point somewhere else), and it leaves the `lobby` Script Disabled
-- so it cannot run blind before a human has looked at it. Untick Disabled when you are ready.
local PARTS = {
@@PARTS@@
}

local function segments(path)
    local out = {}
    for s in string.gmatch(path, "[^/]+") do out[#out + 1] = s end
    return out
end

-- Resolve a path like "ServerScriptService/SHANKPIT460/net460" to the instance, or nil plus where it stopped.
local function findPath(path)
    local segs = segments(path)
    local ok, cur = pcall(function() return game:GetService(segs[1]) end)
    if not ok or cur == nil then return nil, segs[1] end
    for i = 2, #segs do
        local nxt = cur:FindFirstChild(segs[i])
        if nxt == nil then return nil, segs[i] end
        cur = nxt
    end
    return cur, nil
end

local installed, replaced = 0, 0
for _, part in ipairs(PARTS) do
    local existing = findPath(part.path)
    if existing ~= nil then
        existing:Destroy()
        replaced = replaced + 1
    end
    local parentPath = string.match(part.path, "^(.*)/[^/]+$")
    local parent = nil
    if parentPath ~= nil then
        parent = findPath(parentPath)
    end
    if parent == nil then
        error("SHANKPIT460: cannot find the parent of " .. part.path ..
              " -- is this the base place? (a Folder needs ServerScriptService)")
    end
    local inst = Instance.new(part.class)
    inst.Name = part.name
    if part.source ~= nil then
        inst.Source = part.source
    end
    if part.disabled ~= nil then
        inst.Disabled = part.disabled
    end
    inst.Parent = parent
    installed = installed + 1
end

-- Report the two settings a working lobby needs, without changing either: a place's security posture is the
-- owner's decision, and an installer that flipped it would be doing more than it says.
local httpState = "unknown"
pcall(function()
    httpState = tostring(game:GetService("HttpService").HttpEnabled)
end)

print(string.format("SHANKPIT460: %d instances installed (%d replaced)", installed, replaced))
print("  server:  " .. @@SERVER@@ .. "  (Script `lobby` is Disabled)")
print("  client:  " .. @@CLIENT@@ .. "/lobby_client")
print("  HttpService.HttpEnabled = " .. httpState ..
      "  -- needs true (Game Settings > Security > Allow HTTP Requests)")
print("  DataStore needs Studio API access (Game Settings > Security > Enable Studio Access to API Services)")
print("  then untick Disabled on ServerScriptService." .. "__FOLDER__" .. ".lobby")
'''.replace("__FOLDER__", FOLDER)


if __name__ == "__main__":
    main(sys.argv)
