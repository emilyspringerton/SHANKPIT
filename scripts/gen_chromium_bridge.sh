#!/usr/bin/env bash
# gen_chromium_bridge.sh -- regenerate packages/chromium_bridge/{webdriver_gen.inc,wd_rename.h,runtime/*} from a
# sibling ../PARENA checkout: PARENA's WebDriver client, base64 and PNG decoder for the phone's web-game STOPGAP
# (phone_chromium.h). Same single-TU rename pattern as gen_pellegrino_embed.sh: the checked-in outputs are the build
# inputs, CI never needs PARENA. Needs ../PARENA built (parena or .parena-bootstrap) and binutils nm.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
P="${PARENA:-$root/../PARENA}"; S="$P/stdlib"; D="$root/packages/chromium_bridge"
if [ -x "$P/parena" ]; then pb="$P/parena"; else (cd "$P" && make .parena-bootstrap >/dev/null); pb="$P/.parena-bootstrap"; fi
mkdir -p "$D/runtime/aead"
"$pb" build "$S/string.prn" "$S/json.prn" "$S/net/tcp.prn" "$S/net/http.prn" "$S/net/webdriver.prn" \
  "$S/bytes.prn" "$S/base64.prn" "$S/compress/inflate.prn" "$S/image/png.prn" -o "$D/webdriver_gen.inc"
sed -i 's|#include "parena_runtime.h"|#include "runtime/parena_runtime.h"|' "$D/webdriver_gen.inc"
cp "$P/runtime/parena_runtime.h" "$P/runtime/parena_runtime.c" "$D/runtime/"
cp "$P/runtime/aead/monocypher.h" "$D/runtime/aead/"
pr="$(git -C "$P" rev-parse --short HEAD)"
printf '/* generated by scripts/gen_chromium_bridge.sh: PARENA %s -- do not edit */\n' "$pr" > "$D/wd_rename.h"
: > "$D/.rename_probe.h"
cc -std=gnu99 -w -c -DWD_RENAME_HEADER='".rename_probe.h"' -I"$D" "$D/phone_chromium.c" -o "$D/.probe.o"
nm -g --defined-only "$D/.probe.o" | awk '$2 ~ /^[TDBRC]$/ {print $3}' | grep -v '^phc_' | LC_ALL=C sort -u \
  | awk '{printf "#define %s phw_%s\n", $1, $1}' >> "$D/wd_rename.h"
rm -f "$D/.rename_probe.h" "$D/.probe.o"
echo "chromium_bridge regenerated: PARENA $pr, $(grep -c '^#define' "$D/wd_rename.h") renames"
