#!/usr/bin/env bash
# gen_pellegrino_embed.sh -- regenerate packages/pellegrino_embed/{pellegrino_gen.inc,pg_rename.h,runtime/*}
# from sibling ../PELLEGRINO and ../PARENA checkouts (kanban #627). The checked-in outputs are the build
# inputs; CI never needs those repos. Needs a built ../PARENA/parena, SDL2 headers, binutils nm.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
P="${PARENA:-$root/../PARENA}"; G="${PELLEGRINO:-$root/../PELLEGRINO}"
S="$P/stdlib"; D="$root/packages/pellegrino_embed"
mkdir -p "$D/runtime/aead"
"$P/parena" build "$S/string.prn" "$S/array.prn" "$S/io.prn" "$S/sdl2.prn" "$S/bytes.prn" \
  "$S/compress/inflate.prn" "$S/image/png.prn" "$S/image/store.prn" "$S/net/stream.prn" "$G/pellegrino.prn" \
  -o "$D/pellegrino_gen.inc"
# the generated code says #include "parena_runtime.h"; pin it to the vendored copy (the lobby's -Ipackages/world
# would otherwise resolve that name to its own, narrower runtime header)
sed -i 's|#include "parena_runtime.h"|#include "runtime/parena_runtime.h"|' "$D/pellegrino_gen.inc"
cp "$P/runtime/parena_runtime.h" "$P/runtime/parena_runtime.c" "$D/runtime/"
cp "$P/runtime/aead/monocypher.h" "$D/runtime/aead/"
pr="$(git -C "$P" rev-parse --short HEAD)"; gr="$(git -C "$G" rev-parse --short HEAD)"
printf '/* generated by scripts/gen_pellegrino_embed.sh: PELLEGRINO %s + PARENA %s -- do not edit */\n' "$gr" "$pr" > "$D/pg_rename.h"
# pass 1: with an empty rename header, list every global the engine+runtime define (all but the os_menu_* API)
: > "$D/.rename_probe.h"
cc -std=gnu99 -w -c -DPG_RENAME_HEADER='".rename_probe.h"' -I"$D" "$D/os_menu_embed.c" -o "$D/.probe.o"
nm -g --defined-only "$D/.probe.o" | awk '$2 ~ /^[TDBRC]$/ {print $3}' | grep -v '^os_menu_' | LC_ALL=C sort -u \
  | awk '{printf "#define %s pgm_%s\n", $1, $1}' >> "$D/pg_rename.h"
rm -f "$D/.rename_probe.h" "$D/.probe.o"
echo "pellegrino_embed regenerated: PELLEGRINO $gr, PARENA $pr, $(grep -c '^#define' "$D/pg_rename.h") renames"
