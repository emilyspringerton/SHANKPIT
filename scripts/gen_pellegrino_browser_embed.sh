#!/usr/bin/env bash
# gen_pellegrino_browser_embed.sh -- regenerate packages/pellegrino_browser_embed/{pellegrino_gen.inc,
# pg_rename.h,runtime/*} from sibling ../PELLEGRINO and ../PARENA checkouts (SHANKPIT-PELLEGRINO-APP-02:
# the real in-phone browser, as opposed to packages/pellegrino_embed's static, never-navigates OS menu).
#
# Differs from scripts/gen_pellegrino_embed.sh in three ways:
#   1. the `parena build` input list adds the HTTP/3 stack (net/quic_wire, net/h3_wire,
#      crypto/quic_crypto, net/quic_tls, net/quic_client) so embed-nav-start can really dispatch
#      https:// and h3:// navigation, not just http://.
#   2. the probe-based rename pass writes pgb_<name> (not pgm_<name>), so this TU's globals never
#      collide with packages/pellegrino_embed's own pgm_* names when both link into one apps/lobby
#      binary.
#   3. the probe build needs real mbedTLS headers (parena_runtime.h's TLS half is gated on
#      PARENA_WITH_TLS, #include <mbedtls/...>) -- fetched via PELLEGRINO's own
#      scripts/fetch_mbedtls.sh (same pinned source package_windows.sh already uses), plus
#      PELLEGRINO's pellegrino_user_config.h vendored alongside the other runtime copies below.
#
# The checked-in outputs are the build inputs; CI never needs ../PELLEGRINO/../PARENA checked out
# to BUILD this package, but the Makefile's own lobby target still fetches/builds real mbedTLS from
# ../PELLEGRINO's pin (third_party/mbedtls/mbedtls.env) the same way package_windows.sh does, since
# vendoring mbedTLS's own ~200 sources into SHANKPIT too would duplicate PELLEGRINO's one pinned copy.
# Needs a built ../PARENA/parena, SDL2 headers, binutils nm, curl (for the mbedTLS fetch).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
P="${PARENA:-$root/../PARENA}"; G="${PELLEGRINO:-$root/../PELLEGRINO}"
S="$P/stdlib"; D="$root/packages/pellegrino_browser_embed"
mkdir -p "$D/runtime/aead"
"$P/parena" build "$S/string.prn" "$S/array.prn" "$S/io.prn" "$S/sdl2.prn" "$S/bytes.prn" \
  "$S/compress/inflate.prn" "$S/image/png.prn" "$S/image/store.prn" "$S/net/stream.prn" \
  "$S/net/quic_wire.prn" "$S/net/h3_wire.prn" "$S/crypto/quic_crypto.prn" "$S/net/quic_tls.prn" \
  "$S/net/quic_client.prn" "$G/pellegrino.prn" \
  -o "$D/pellegrino_gen.inc"
# the generated code says #include "parena_runtime.h"; pin it to the vendored copy (the lobby's -Ipackages/world
# would otherwise resolve that name to its own, narrower runtime header)
sed -i 's|#include "parena_runtime.h"|#include "runtime/parena_runtime.h"|' "$D/pellegrino_gen.inc"
cp "$P/runtime/parena_runtime.h" "$P/runtime/parena_runtime.c" "$D/runtime/"
cp "$P/runtime/aead/monocypher.h" "$P/runtime/aead/monocypher.c" "$D/runtime/aead/"
cp "$G/third_party/mbedtls/pellegrino_user_config.h" "$D/runtime/"
MB="$(bash "$G/scripts/fetch_mbedtls.sh")"
pr="$(git -C "$P" rev-parse --short HEAD)"; gr="$(git -C "$G" rev-parse --short HEAD)"
printf '/* generated by scripts/gen_pellegrino_browser_embed.sh: PELLEGRINO %s + PARENA %s -- do not edit */\n' "$gr" "$pr" > "$D/pg_rename.h"
# pass 1: with an empty rename header, list every global the engine+runtime define (all but the
# phone_browser_* API), same probe technique gen_pellegrino_embed.sh uses -- just a different prefix.
: > "$D/.rename_probe.h"
cc -std=gnu99 -w -c -DPG_RENAME_HEADER='".rename_probe.h"' \
   -DPARENA_WITH_TLS -DPARENA_TLS_STATIC_HEAP -DPARENA_TLS_HEAP_STATS -DPARENA_WITH_QUIC_CRYPTO \
   "-DMBEDTLS_USER_CONFIG_FILE=\"pellegrino_user_config.h\"" \
   -I"$D" -I"$D/runtime" -I"$MB/include" \
   "$D/phone_browser_embed.c" -o "$D/.probe.o"
nm -g --defined-only "$D/.probe.o" | awk '$2 ~ /^[TDBRC]$/ {print $3}' | grep -v '^phone_browser_' | LC_ALL=C sort -u \
  | awk '{printf "#define %s pgb_%s\n", $1, $1}' >> "$D/pg_rename.h"
rm -f "$D/.rename_probe.h" "$D/.probe.o"
echo "pellegrino_browser_embed regenerated: PELLEGRINO $gr, PARENA $pr, $(grep -c '^#define' "$D/pg_rename.h") renames"
