#!/usr/bin/env bash
# Regenerates packages/common/wm_rules_gen.h from PARENA/stdlib/worldmap/wm_rules.prn with BURROW's C target.
# Functions become static, prefixed wm_ (the engine is one big translation unit; unprefixed names would collide).
set -euo pipefail
cd "$(dirname "$0")/.."
SRC="${WM_RULES_PRN:-../PARENA/stdlib/worldmap/wm_rules.prn}"
BURROW="${BURROW:-burrow}"
T="$(mktemp)"; trap 'rm -f "$T"' EXIT
"$BURROW" build "$SRC" -o "$T" >/dev/null
python3 - "$T" > packages/common/wm_rules_gen.h <<'PY'
import re,sys
c=open(sys.argv[1]).read()
c=re.sub(r'#include "parena_runtime.h"\n','',c)
names=sorted(set(re.findall(r'^(?:int|float|double)\s+(\w+)\(',c,re.M)),key=len,reverse=True)
for n in names: c=re.sub(r'\b'+n+r'\b','wm_'+n,c)
c=re.sub(r'^(int|float|double)\s+(wm_\w+\()',r'static inline \1 \2',c,flags=re.M)
print("#ifndef SHANKPIT_WM_RULES_GEN_H\n#define SHANKPIT_WM_RULES_GEN_H\n/* GENERATED by scripts/regen_wm_rules.sh from PARENA/stdlib/worldmap/wm_rules.prn (the WORLDMAP contract). Do not edit. */")
print(c); print("#endif")
PY
