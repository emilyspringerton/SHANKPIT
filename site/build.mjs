// site/build.mjs -- assemble _site/ for GitHub Pages.
//
//   node site/build.mjs
//
// The site is deliberately almost static: index.html and style.css are authored, and docs.html is GENERATED from
// the markdown that already lives in docs/ and docs2/, with each entry linking to the file on GitHub. Nothing is
// copied, so there is only ever one copy of a design document -- the same rule the engine follows for its rules.
//
// Missing files are a hard error here rather than a silently half-built site, because the only consumer is a CI job
// that will happily publish whatever it is handed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const out = path.resolve(root, '_site');
const REPO = 'https://github.com/emilyspringerton/SHANKPIT/blob/master';

const die = (msg) => { console.error('site/build: ' + msg); process.exit(1); };

function readDir(dir) {
  const full = path.join(root, dir);
  if (!fs.existsSync(full)) die(`no ${dir}/ directory`);
  return fs.readdirSync(full)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => {
      const text = fs.readFileSync(path.join(full, f), 'utf8');
      const heading = text.match(/^#\s+(.+)$/m);
      const title = (heading ? heading[1] : f.replace(/\.md$/, ''))
        .replace(/[`*_]/g, '')
        .replace(/\s+/g, ' ')
        .trim();
      const firstPara = text
        .split('\n')
        .map((l) => l.trim())
        .find((l) => l && !l.startsWith('#') && !l.startsWith('|') && !l.startsWith('-') && !l.startsWith('>'));
      return {
        file: f,
        href: `${REPO}/${dir}/${encodeURIComponent(f)}`,
        title,
        note: firstPara ? firstPara.replace(/[`*_]/g, '').slice(0, 180) : '',
      };
    });
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

const docs = readDir('docs');
const docs2 = readDir('docs2');
if (docs.length === 0) die('docs/ has no markdown');
if (docs2.length === 0) die('docs2/ has no markdown');

const rows = (list) => list.map((d) => `      <li><a href="${esc(d.href)}">${esc(d.title)}</a>` +
  (d.note ? `<span class="note">${esc(d.note)}</span>` : '') +
  `<span class="path">${esc(d.file)}</span></li>`).join('\n');

const docsPage = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="theme-color" content="#07090a">
<meta name="description" content="Every SHANKPIT design document, northstar and post-mortem, in one index.">
<title>Documents &mdash; SHANKPIT</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<main class="wrap">
  <header class="hero">
    <p class="eyebrow">SHANKPIT &middot; the record</p>
    <h1>Documents</h1>
    <p class="lede">${docs.length + docs2.length} documents, linked straight into the repository. This page is
      generated at build time from the files that are actually there &mdash; it cannot drift from them.</p>
    <nav class="links" aria-label="Back">
      <a class="go" href="./">Back to SHANKPIT</a>
      <a class="go go--alt" href="https://github.com/emilyspringerton/SHANKPIT/tree/master/docs">docs on GitHub</a>
    </nav>
  </header>

  <section class="docgroup" aria-labelledby="d1">
    <h2 id="d1">docs/ &mdash; northstars, systems, affordances (${docs.length})</h2>
    <ul class="docs">
${rows(docs)}
    </ul>
  </section>

  <section class="docgroup" aria-labelledby="d2">
    <h2 id="d2">docs2/ &mdash; specs and the shared-engine record (${docs2.length})</h2>
    <ul class="docs">
${rows(docs2)}
    </ul>
  </section>

  <footer class="foot">
    <p><a href="https://github.com/emilyspringerton/SHANKPIT">source</a> &middot;
      <a href="https://wotan.okemily.com/">WOTAN</a></p>
    <p class="dim">Generated by site/build.mjs, published by GitHub Actions.</p>
  </footer>
</main>
</body>
</html>
`;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

for (const file of ['index.html', 'style.css']) {
  const from = path.join(here, file);
  if (!fs.existsSync(from)) die(`no site/${file}`);
  fs.copyFileSync(from, path.join(out, file));
}

// shankpit-460, the playable build, served from THIS deploy at /SHANKPIT/shankpit-460/.
//
// It is not authored here: WOTAN/shankpit-460 is the one home for the three files, and this copies them at
// build time (CI checks WOTAN out into vendor/wotan; locally the sibling ../WOTAN is used). Vendoring at build
// time instead of committing a second copy keeps the two from drifting -- the same rule the rules files follow.
//
// The catching detail: WOTAN serves at the domain root, so its pages say href="/css/wotan-hs.css". A project
// page lives at /SHANKPIT/, where a leading / is the domain root and 404s, so each root-absolute ref is rebased
// to the page's own depth and its target copied too. A ref that resolves to nothing in the WOTAN checkout is a
// hard error, not a broken link published to the web.
const WOTAN_CHECKOUTS = [path.resolve(root, 'vendor/wotan'), path.resolve(root, '..', 'WOTAN')];
const wotan = WOTAN_CHECKOUTS.find((p) => fs.existsSync(path.join(p, 'shankpit-460', 'index.html')));
if (!wotan) die(`no WOTAN checkout found (looked in ${WOTAN_CHECKOUTS.map((p) => path.relative(root, p)).join(', ')})`);

const gameDir = path.join(wotan, 'shankpit-460');
const outGame = path.join(out, 'shankpit-460');
fs.mkdirSync(outGame, { recursive: true });

let copiedAssets = 0;
for (const file of fs.readdirSync(gameDir).sort()) {
  const from = path.join(gameDir, file);
  if (!fs.statSync(from).isFile()) continue;
  const to = path.join(outGame, file);
  if (!file.endsWith('.html')) { fs.copyFileSync(from, to); continue; }

  const targets = new Set();
  const text = fs.readFileSync(from, 'utf8').replace(/(href|src)="\/([^"]*)"/g, (_m, attr, rest) => {
    targets.add(rest);
    return `${attr}="../${rest}"`;
  });
  fs.writeFileSync(to, text);

  for (const ref of targets) {
    const target = ref.split('#')[0].split('?')[0];
    if (!target) continue;
    const src = path.join(wotan, target);
    if (!fs.existsSync(src)) die(`shankpit-460/index.html references ${ref}, absent from the WOTAN checkout`);
    const dst = path.join(out, target);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    copiedAssets++;
  }
}
console.log(`site/build: shankpit-460/ vendored from ${path.relative(root, wotan) || '.'} [${copiedAssets} referenced assets]`);
fs.writeFileSync(path.join(out, 'docs.html'), docsPage);
// Pages' Jekyll pipeline must not touch a site that is already HTML; this is the standard opt-out.
fs.writeFileSync(path.join(out, '.nojekyll'), '');
// A build stamp so the deployed site says which commit it came from, for when it looks stale.
fs.writeFileSync(path.join(out, 'build.json'), JSON.stringify({
  commit: process.env.GITHUB_SHA || null,
  ref: process.env.GITHUB_REF_NAME || null,
  run: process.env.GITHUB_RUN_ID || null,
  built_at: new Date().toISOString(),
  docs: { docs: docs.length, docs2: docs2.length },
}, null, 2) + '\n');

console.log(`site/build: _site/ [${docs.length + docs2.length} documents indexed]`);
