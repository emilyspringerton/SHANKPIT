#!/usr/bin/env python3
"""update_baked_level.py -- refresh ONE entry of packages/world/baked_levels_gen.h from a level file.

Why this exists: `scripts/bake_levels.py` bakes the whole table from a live IDUNA, which is the right
way to do a full refresh but needs a server. When a level is edited in the repo (or generated by
`tools/build_loft_city.py`) and the live build has to serve it, this patches exactly that one export
plus its registry metadata -- id, name and every count stay consistent, and the other 64 levels are
re-emitted untouched, so the diff is the level you changed and nothing else.

Default target is the level the ZOMBIES sandbox loads (the registry entry with `is_zombie_default`,
see apps/lobby/src/main.c:lobby_zombies_load_level) -- the "live" nextown map.

    python3 tools/update_baked_level.py --level var/zombie/nextown_zombies.json
    python3 tools/update_baked_level.py --level var/maps/proc_x.json --id 92
    python3 tools/update_baked_level.py --level ... --touch   # also bump updated_at

Output is deterministic apart from `--touch`: the same input produces a byte-identical header.
"""
import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "packages", "world", "baked_levels_gen.h")

LIT = r'"(?:[^"\\]|\\.)*"'


def c_unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\"}.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def c_literal(s, indent="    "):
    out = []
    for i in range(0, len(s), 100):
        chunk = s[i:i + 100].replace("\\", "\\\\").replace('"', '\\"')
        out.append(indent + '"' + chunk + '"')
    return "\n".join(out) if out else indent + '""'


def parse_header(src):
    def table(name):
        m = re.search(r"static const char %s\[\] =\n(.*?);\n" % name, src, re.S)
        if not m:
            raise SystemExit("could not find %s in the baked header" % name)
        # strip each literal's own quotes before unescaping: c_unescape on the whole match would leave
        # them in and json.loads would read `""` as an empty string followed by extra data
        return json.loads("".join(c_unescape(x[1:-1]) for x in re.findall(LIT, m.group(1))))

    main = table("BAKED_REGISTRY_MAIN")
    zom = table("BAKED_REGISTRY_ZOMBIES")

    m = re.search(r"BAKED_LEVEL_EXPORTS\[\] = \{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("could not find BAKED_LEVEL_EXPORTS")
    exports = {}
    for lid, body in re.findall(r"\{\s*(\d+),\s*((?:%s\s*)+)\}," % LIT, m.group(1)):
        exports[int(lid)] = "".join(c_unescape(x[1:-1]) for x in re.findall(LIT, body))
    if not exports:
        raise SystemExit("no baked exports parsed")
    return main, zom, exports


def emit(main, zom, exports, src):
    head = src.split("static const char BAKED_REGISTRY_MAIN[] =")[0].rstrip("\n")
    truthful = re.search(r"baked_levels_gen\.h -- GENERATED by .*", src)
    lines = [head, ""] if head else []
    lines += [
        "static const char BAKED_REGISTRY_MAIN[] =",
        c_literal(json.dumps(main, separators=(",", ":"))) + ";",
        "",
        "static const char BAKED_REGISTRY_ZOMBIES[] =",
        c_literal(json.dumps(zom, separators=(",", ":"))) + ";",
        "",
        "typedef struct { int id; const char *json; } BakedLevelExport;",
        "static const BakedLevelExport BAKED_LEVEL_EXPORTS[] = {",
    ]
    for lid in sorted(exports):
        lines.append("    { %d," % lid)
        lines.append(c_literal(exports[lid], "      ") + " },")
    lines += ["};", "#define BAKED_LEVEL_EXPORT_COUNT %d" % len(exports), "", "#endif", ""]
    _ = truthful
    return "\n".join(lines)


def level_meta(doc):
    walls = doc.get("walls") or []
    return {
        "width": doc.get("width"),
        "height": doc.get("height"),
        "depth": doc.get("depth"),
        "ground_plane_enabled": doc.get("ground_plane_enabled"),
        "ground_plane_squares": doc.get("ground_plane_squares"),
        "wall_count": len(walls),
        "spawner_count": len(doc.get("spawners") or []),
        "door_count": len(doc.get("doors") or []),
        "nav_node_count": len(doc.get("nav_nodes") or []),
        "character_count": len(doc.get("characters") or []),
        "level_exit_count": len(doc.get("level_exits") or []),
    }


def main_argv():
    ap = argparse.ArgumentParser()
    ap.add_argument("--level", required=True, help="level JSON to bake in")
    ap.add_argument("--id", type=int, default=None, help="baked level id (default: the zombie default)")
    ap.add_argument("--out", default=HEADER)
    ap.add_argument("--touch", action="store_true", help="also stamp updated_at to now")
    args = ap.parse_args()

    doc = json.load(open(args.level))
    src = open(args.out).read()
    main, zom, exports = parse_header(src)

    target = args.id
    if target is None:
        defaults = [e for e in zom if e.get("is_zombie_default")]
        if not defaults:
            raise SystemExit("no is_zombie_default entry in the baked zombies registry -- pass --id")
        target = defaults[0]["id"]
    if target not in exports:
        raise SystemExit("baked table has no export for id %d" % target)

    before = json.loads(exports[target])
    n_before = len(before.get("walls") or [])

    meta = level_meta(doc)
    found = False
    for table in (main, zom):
        for ent in table:
            if ent.get("id") != target:
                continue
            found = True
            for k, v in meta.items():
                if v is not None:
                    ent[k] = v
            if args.touch:
                ent["updated_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if not found:
        print("warn: id %d is not in either registry list (export patched anyway)" % target, file=sys.stderr)

    exports[target] = json.dumps(doc, separators=(",", ":"))
    out = emit(main, zom, exports, src)
    if out == src:
        print("no change: %s already matches %s" % (args.out, args.level))
        return 0
    open(args.out, "w").write(out)
    print("baked level %d: %d walls -> %d walls, %d exports, %d bytes"
          % (target, n_before, len(doc.get("walls") or []), len(exports), len(out)))
    return 0


if __name__ == "__main__":
    sys.exit(main_argv())
